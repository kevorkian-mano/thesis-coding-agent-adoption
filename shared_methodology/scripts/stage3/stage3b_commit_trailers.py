import os
import re
import time
import requests
import pandas as pd
from pathlib import Path

# ── paths ─────────────────────────────────────────────────────────────────────
ROOT      = Path(__file__).resolve().parents[2]
OUT_DIR   = ROOT / "data" / "stage3"
IN_FILE   = OUT_DIR / "pass1_unclassified.csv"
OUT_PASS2 = OUT_DIR / "pass2_results.csv"
OUT_UNRES = OUT_DIR / "pass2_unclassified.csv"

TOKEN = os.environ.get("GITHUB_TOKEN", "")
if not TOKEN:
    raise SystemExit("Set GITHUB_TOKEN environment variable before running.")

HEADERS  = {"Authorization": f"token {TOKEN}", "Accept": "application/vnd.github+json"}
REST_URL = "https://api.github.com"
SLEEP_OK    = 0.5
SLEEP_RETRY = 60
MAX_COMMITS = 100
MAX_PRS     = 50
SAVE_EVERY  = 200   # save to disk every N repos

# ── trailer / commit-body patterns ────────────────────────────────────────────
# Matched against the full commit message string (message + trailers block).
# One match per commit (break after first match per commit).
TRAILER_PATTERNS = [
    # Claude Code
    (re.compile(r"co-authored-by:.*claude.*anthropic",        re.I),  "Claude Code"),
    (re.compile(r"noreply@anthropic\.com",                    re.I),  "Claude Code"),
    (re.compile(r"generated with claude code",                re.I),  "Claude Code"),
    (re.compile(r"generated by claude",                       re.I),  "Claude Code"),
    # GitHub Copilot
    (re.compile(r"co-authored-by:.*copilot",                  re.I),  "GitHub Copilot"),
    (re.compile(r"github-actions\[bot\].*copilot",            re.I),  "GitHub Copilot"),
    # Devin
    (re.compile(r"co-authored-by:.*devin",                    re.I),  "Devin"),
    # Cursor
    (re.compile(r"co-authored-by:.*cursor",                   re.I),  "Cursor"),
    # Aider
    (re.compile(r"co-authored-by:.*aider",                    re.I),  "Aider"),
    (re.compile(r"noreply@aider\.chat",                       re.I),  "Aider"),
    # Codeium / Windsurf
    (re.compile(r"co-authored-by:.*codeium",                  re.I),  "Codeium"),
    (re.compile(r"co-authored-by:.*windsurf",                 re.I),  "Windsurf"),
    # Gemini
    (re.compile(r"co-authored-by:.*gemini",                   re.I),  "Gemini CLI"),
    # Replit
    (re.compile(r"replit-commit-author:",                     re.I),  "Replit"),
    (re.compile(r"generated by replit",                       re.I),  "Replit"),
    # OpenAI Codex
    (re.compile(r"generated by codex",                        re.I),  "OpenAI Codex"),
    (re.compile(r"codex-cli",                                 re.I),  "OpenAI Codex"),
    (re.compile(r"noreply@openai\.com",                       re.I),  "OpenAI Codex"),
    # Mistral Vibe
    (re.compile(r"vibe@mistral\.ai",                          re.I),  "Mistral Vibe"),
    (re.compile(r"co-authored-by:.*mistral",                  re.I),  "Mistral Vibe"),
    # Abacus AI
    (re.compile(r"agent@abacus\.ai",                          re.I),  "Abacus AI"),
    # Paperclip
    (re.compile(r"noreply@paperclip\.ing",                    re.I),  "Paperclip"),
    # Microsoft Amplifier
    (re.compile(r"microsoft-amplifier@users\.noreply\.github\.com", re.I), "Microsoft Amplifier"),
    # Letta Code
    (re.compile(r"co-authored-by:.*letta",                    re.I),  "Letta Code"),
]

# ── author name suffix patterns ───────────────────────────────────────────────
# Checked against the commit author's display NAME (not email).
# Aider appends " (aider)" to the author name when making commits.
AUTHOR_NAME_PATTERNS = [
    (re.compile(r"\(aider\)\s*$", re.I), "Aider"),
]

# ── PR branch prefix patterns ─────────────────────────────────────────────────
PR_BRANCH_PATTERNS = [
    (re.compile(r"^copilot/",      re.I),  "GitHub Copilot"),
    (re.compile(r"^codex/",        re.I),  "OpenAI Codex"),
    (re.compile(r"^devin/",        re.I),  "Devin"),
    (re.compile(r"^claude/",       re.I),  "Claude Code"),
    (re.compile(r"^cursor/",       re.I),  "Cursor"),
    (re.compile(r"^jules[-/]",     re.I),  "Jules"),
    (re.compile(r"^sweep/",        re.I),  "Sweep"),
    (re.compile(r"^openhands/",    re.I),  "OpenHands"),
    (re.compile(r"^windsurf-bot/", re.I),  "Windsurf"),
    (re.compile(r"^goose/",        re.I),  "Goose"),
    (re.compile(r"^serena/",       re.I),  "Serena"),
    (re.compile(r"^gru/",          re.I),  "Gru"),
    (re.compile(r"^open-swe/",     re.I),  "Open SWE"),
    (re.compile(r"^replit/",       re.I),  "Replit"),
    (re.compile(r"^amazon-q/",     re.I),  "Amazon Q"),
    (re.compile(r"^pr-agent/",     re.I),  "PR-Agent"),
]


def get_commits(owner: str, name: str) -> list[dict]:
    """Return list of commit dicts (up to MAX_COMMITS). Each dict has 'message' and 'author_name'."""
    url    = f"{REST_URL}/repos/{owner}/{name}/commits"
    params = {"per_page": MAX_COMMITS}
    for attempt in range(5):
        try:
            resp = requests.get(url, headers=HEADERS, params=params, timeout=20)
            if resp.status_code == 200:
                result = []
                for c in resp.json():
                    commit_data = c.get("commit") or {}
                    author_data = commit_data.get("author") or {}
                    result.append({
                        "message":     commit_data.get("message") or "",
                        "author_name": author_data.get("name")    or "",
                    })
                return result
            elif resp.status_code in (403, 429):
                time.sleep(SLEEP_RETRY)
            else:
                time.sleep(5)
        except Exception as e:
            wait = 10 * (attempt + 1)
            print(f"  Network error ({e.__class__.__name__}), retry {attempt+1}/5 in {wait}s ...")
            time.sleep(wait)
    return []


def get_pr_branches(owner: str, name: str) -> list[str]:
    """Return list of PR head branch names."""
    url    = f"{REST_URL}/repos/{owner}/{name}/pulls"
    params = {"state": "all", "per_page": MAX_PRS}
    for attempt in range(5):
        try:
            resp = requests.get(url, headers=HEADERS, params=params, timeout=20)
            if resp.status_code == 200:
                return [pr.get("head", {}).get("ref", "") for pr in resp.json()]
            elif resp.status_code in (403, 429):
                time.sleep(SLEEP_RETRY)
            else:
                time.sleep(5)
        except Exception as e:
            wait = 10 * (attempt + 1)
            print(f"  Network error ({e.__class__.__name__}), retry {attempt+1}/5 in {wait}s ...")
            time.sleep(wait)
    return []


def scan_repo(owner: str, name: str) -> tuple[int, set, str]:
    """
    Scan commits (messages + author names) and PR branch names.
    Returns (hit_count, agents_found_set, signal_source_string).
    """
    agents_found = {}   # agent -> True (insertion-ordered, dedup)
    hit_count    = 0
    sources      = set()

    # ── commit scan ───────────────────────────────────────────────────────────
    commits = get_commits(owner, name)

    for commit in commits:
        msg         = commit["message"]
        author_name = commit["author_name"]
        matched     = False

        # Trailer / body patterns
        for pattern, agent in TRAILER_PATTERNS:
            if pattern.search(msg):
                agents_found[agent] = True
                hit_count += 1
                sources.add("commit_trailer")
                matched = True
                break

        # Author name suffix (only if no trailer match for this commit)
        if not matched:
            for pattern, agent in AUTHOR_NAME_PATTERNS:
                if pattern.search(author_name):
                    agents_found[agent] = True
                    hit_count += 1
                    sources.add("commit_trailer")
                    break

    # ── PR branch scan (only if no commits matched -- saves API calls) ────────
    if hit_count == 0:
        branches = get_pr_branches(owner, name)
        for branch in branches:
            for pattern, agent in PR_BRANCH_PATTERNS:
                if pattern.search(branch):
                    agents_found[agent] = True
                    hit_count += 1
                    sources.add("pr_branch")
                    break

    source_str = "|".join(sorted(sources))
    return hit_count, set(agents_found.keys()), source_str


def classify(hit_count: int) -> str:
    # commit_trailer and pr_branch are STRONG signals under the tiered rule.
    # Any hit -> agentic. Never produce "ai_assisted" here.
    return "agentic" if hit_count > 0 else "unclassified"


# ── main ──────────────────────────────────────────────────────────────────────
def main():
    print("Stage 3b -- Pass B: Commit Trailer Scan")
    print("=" * 55)

    if not IN_FILE.exists():
        raise SystemExit(f"Run stage3a first. Missing: {IN_FILE}")

    repos = pd.read_csv(IN_FILE)["full_name"].tolist()
    print(f"Repos to process: {len(repos):,}")

    # Resume support
    if OUT_PASS2.exists():
        done  = set(pd.read_csv(OUT_PASS2)["full_name"].tolist())
        repos = [r for r in repos if r not in done]
        print(f"Resuming: {len(repos):,} remaining")

    results       = []
    total         = len(repos)
    agentic_count = 0

    for i, full_name in enumerate(repos):
        parts = full_name.split("/", 1)
        if len(parts) != 2:
            continue
        owner, name = parts

        for _attempt in range(3):
            try:
                hit_count, agents_found, source = scan_repo(owner, name)
                break
            except Exception as e:
                print(f"  Error on {full_name}: {e}")
                time.sleep(10)
        else:
            hit_count, agents_found, source = 0, set(), ""

        label = classify(hit_count)
        if label == "agentic":
            agentic_count += 1

        results.append({
            "full_name":      full_name,
            "trailer_count":  hit_count,
            "agents_found":   "|".join(sorted(agents_found)),
            "adoption_label": label,
            "signal_source":  source,
        })

        if (i + 1) % SAVE_EVERY == 0 or (i + 1) == total:
            pct = (i + 1) / total * 100
            print(f"  {i+1:>6,}/{total:,} ({pct:.1f}%)  agentic: {agentic_count:,}")
            chunk = pd.DataFrame(results)
            if OUT_PASS2.exists():
                existing = pd.read_csv(OUT_PASS2)
                chunk    = pd.concat([existing, chunk], ignore_index=True)
            chunk.to_csv(OUT_PASS2, index=False)
            results = []

        time.sleep(SLEEP_OK)

    # Final buffer flush
    if results:
        chunk = pd.DataFrame(results)
        if OUT_PASS2.exists():
            existing = pd.read_csv(OUT_PASS2)
            chunk    = pd.concat([existing, chunk], ignore_index=True)
        chunk.to_csv(OUT_PASS2, index=False)

    new_df = pd.read_csv(OUT_PASS2)

    # Save unclassified for Pass C
    unclassified = new_df[new_df["adoption_label"] == "unclassified"][["full_name"]]
    unclassified.to_csv(OUT_UNRES, index=False)

    # Summary
    total_proc     = len(new_df)
    n_agentic      = (new_df["adoption_label"] == "agentic").sum()
    n_unclassified = (new_df["adoption_label"] == "unclassified").sum()

    print()
    print("=" * 55)
    print(f"Total processed   : {total_proc:,}")
    print(f"Agentic (Pass B)  : {n_agentic:,}  ({n_agentic/total_proc*100:.1f}%)")
    print(f"Unclassified      : {n_unclassified:,}  ({n_unclassified/total_proc*100:.1f}%)  -> pass to stage3c")
    print()
    print("Top agents detected:")
    agent_series = (
        new_df[new_df["agents_found"] != ""]["agents_found"]
        .str.split("|")
        .explode()
    )
    top = agent_series.value_counts()
    for agent, count in top.items():
        print(f"  {agent:<40} {count:>6,}")
    print()
    print(f"Saved: {OUT_PASS2}")
    print(f"Saved: {OUT_UNRES}")


if __name__ == "__main__":
    main()

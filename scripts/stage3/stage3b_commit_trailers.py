#!/usr/bin/env python3
"""
Stage 3b -- Pass 2: Commit Trailer Scan
=========================================
Runs only on repos not classified by Pass 1 (pass1_unclassified.csv).
Fetches the most recent 100 commits per repo and scans commit messages
for known AI agent trailer patterns.

Also checks PR branch names for agent-specific prefixes (copilot/, codex/).
This is done via a single list-PRs REST call per repo.

A repo with trailers found is labelled agentic or ai_assisted:
  - >= 3 AI commits or trailers from 2+ distinct agents -> agentic
  - 1-2 AI commits or trailers from 1 agent -> ai_assisted

Repos with no match are passed to Pass 3 (stage3c).

Output
------
data/stage3/pass2_results.csv
  full_name, trailer_count, agents_found, adoption_label, signal_source

data/stage3/pass2_unclassified.csv
  full_name  (repos with no trailer signal -- input for stage3c)

Usage
-----
  export GITHUB_TOKEN=ghp_...
  python3 scripts/stage3/stage3b_commit_trailers.py
"""

import os
import re
import time
import requests
import pandas as pd
from pathlib import Path

# ── paths ─────────────────────────────────────────────────────────────────────
ROOT      = Path(__file__).resolve().parents[2]
OUT_DIR   = ROOT / "data" / "stage3"
IN_FILE   = OUT_DIR / "pass1_unclassified.csv"
OUT_PASS2 = OUT_DIR / "pass2_results.csv"
OUT_UNRES = OUT_DIR / "pass2_unclassified.csv"

TOKEN = os.environ.get("GITHUB_TOKEN", "")
if not TOKEN:
    raise SystemExit("Set GITHUB_TOKEN environment variable before running.")

HEADERS  = {"Authorization": f"token {TOKEN}", "Accept": "application/vnd.github+json"}
REST_URL = "https://api.github.com"
SLEEP_OK    = 0.5
SLEEP_RETRY = 60
MAX_COMMITS = 100
MAX_PRS     = 50
SAVE_EVERY  = 200   # save to disk every N repos

# ── trailer patterns ───────────────────────────────────────────────────────────
TRAILER_PATTERNS = [
    (re.compile(r"co-authored-by:.*claude.*anthropic", re.I),         "Claude Code"),
    (re.compile(r"co-authored-by:.*github.copilot", re.I),            "GitHub Copilot"),
    (re.compile(r"co-authored-by:.*copilot", re.I),                   "GitHub Copilot"),
    (re.compile(r"co-authored-by:.*devin", re.I),                     "Devin"),
    (re.compile(r"co-authored-by:.*cursor", re.I),                    "Cursor"),
    (re.compile(r"co-authored-by:.*aider", re.I),                     "Aider"),
    (re.compile(r"co-authored-by:.*codeium", re.I),                   "Codeium"),
    (re.compile(r"co-authored-by:.*windsurf", re.I),                  "Windsurf"),
    (re.compile(r"co-authored-by:.*gemini", re.I),                    "Gemini"),
    (re.compile(r"generated with claude code", re.I),                 "Claude Code"),
    (re.compile(r"generated by claude", re.I),                        "Claude Code"),
    (re.compile(r"noreply@anthropic\.com", re.I),                     "Claude Code"),
    (re.compile(r"github-actions\[bot\].*copilot", re.I),             "GitHub Copilot"),
]

PR_BRANCH_PATTERNS = [
    (re.compile(r"^copilot/", re.I),  "GitHub Copilot"),
    (re.compile(r"^codex/", re.I),    "OpenAI Codex"),
    (re.compile(r"^devin/", re.I),    "Devin"),
]

def get_commits(owner: str, name: str) -> list[str]:
    """Return list of commit message strings (up to MAX_COMMITS)."""
    url = f"{REST_URL}/repos/{owner}/{name}/commits"
    params = {"per_page": MAX_COMMITS}
    for attempt in range(5):
        try:
            resp = requests.get(url, headers=HEADERS, params=params, timeout=20)
            if resp.status_code == 200:
                return [(c.get("commit") or {}).get("message") or "" for c in resp.json()]
            elif resp.status_code in (403, 429):
                time.sleep(SLEEP_RETRY)
            else:
                time.sleep(5)
        except Exception as e:
            wait = 10 * (attempt + 1)
            print(f"  Network error ({e.__class__.__name__}), retry {attempt+1}/5 in {wait}s ...")
            time.sleep(wait)
    return []

def get_pr_branches(owner: str, name: str) -> list[str]:
    """Return list of PR head branch names."""
    url = f"{REST_URL}/repos/{owner}/{name}/pulls"
    params = {"state": "all", "per_page": MAX_PRS}
    for attempt in range(5):
        try:
            resp = requests.get(url, headers=HEADERS, params=params, timeout=20)
            if resp.status_code == 200:
                return [pr.get("head", {}).get("ref", "") for pr in resp.json()]
            elif resp.status_code in (403, 429):
                time.sleep(SLEEP_RETRY)
            else:
                time.sleep(5)
        except Exception as e:
            wait = 10 * (attempt + 1)
            print(f"  Network error ({e.__class__.__name__}), retry {attempt+1}/5 in {wait}s ...")
            time.sleep(wait)
    return []

def scan_repo(owner: str, name: str) -> tuple[int, set, str]:
    """
    Returns (trailer_count, agents_found_set, signal_source).
    """
    agents_found = set()
    trailer_count = 0

    # Scan commits
    for attempt in range(3):
        try:
            messages = get_commits(owner, name)
            break
        except Exception:
            time.sleep(5)
    else:
        messages = []

    for msg in messages:
        for pattern, agent in TRAILER_PATTERNS:
            if pattern.search(msg):
                agents_found.add(agent)
                trailer_count += 1
                break  # one match per commit

    # Scan PR branch names
    if trailer_count == 0:  # only if no trailers yet (save API calls)
        for attempt in range(3):
            try:
                branches = get_pr_branches(owner, name)
                break
            except Exception:
                time.sleep(5)
        else:
            branches = []
        for branch in branches:
            for pattern, agent in PR_BRANCH_PATTERNS:
                if pattern.search(branch):
                    agents_found.add(agent)
                    trailer_count += 1
                    break

    source = "commit_trailer" if any(
        any(p.search(m) for p, _ in TRAILER_PATTERNS) for m in messages
    ) else ("pr_branch" if trailer_count > 0 else "")

    return trailer_count, agents_found, source

def classify(trailer_count: int, agents_found: set) -> str:
    if trailer_count == 0:
        return "unclassified"
    if trailer_count >= 3 or len(agents_found) >= 2:
        return "agentic"
    return "ai_assisted"

# ── main ──────────────────────────────────────────────────────────────────────
def main():
    print("Stage 3b -- Pass 2: Commit Trailer Scan")
    print("=" * 55)

    if not IN_FILE.exists():
        raise SystemExit(f"Run stage3a first. Missing: {IN_FILE}")

    repos = pd.read_csv(IN_FILE)["full_name"].tolist()
    print(f"Repos to process: {len(repos):,}")

    # Resume support
    if OUT_PASS2.exists():
        done = set(pd.read_csv(OUT_PASS2)["full_name"].tolist())
        repos = [r for r in repos if r not in done]
        print(f"Resuming: {len(repos):,} remaining")

    results = []
    total   = len(repos)
    agentic_count = 0
    ai_assisted_count = 0

    for i, full_name in enumerate(repos):
        parts = full_name.split("/", 1)
        if len(parts) != 2:
            continue
        owner, name = parts

        for attempt in range(3):
            try:
                trailer_count, agents_found, source = scan_repo(owner, name)
                break
            except Exception as e:
                print(f"  Error on {full_name}: {e}")
                time.sleep(10)
        else:
            trailer_count, agents_found, source = 0, set(), ""

        label = classify(trailer_count, agents_found)
        if label == "agentic":
            agentic_count += 1
        elif label == "ai_assisted":
            ai_assisted_count += 1

        results.append({
            "full_name":      full_name,
            "trailer_count":  trailer_count,
            "agents_found":   "|".join(sorted(agents_found)),
            "adoption_label": label,
            "signal_source":  source,
        })

        if (i + 1) % SAVE_EVERY == 0 or (i + 1) == total:
            pct = (i + 1) / total * 100
            print(f"  {i+1:>6,}/{total:,} ({pct:.1f}%)  "
                  f"agentic: {agentic_count:,}  ai_assisted: {ai_assisted_count:,}")
            # incremental save
            chunk = pd.DataFrame(results)
            if OUT_PASS2.exists():
                existing = pd.read_csv(OUT_PASS2)
                chunk = pd.concat([existing, chunk], ignore_index=True)
            chunk.to_csv(OUT_PASS2, index=False)
            results = []  # clear buffer after saving

        time.sleep(SLEEP_OK)

    # Final save of any remaining buffer
    if results:
        chunk = pd.DataFrame(results)
        if OUT_PASS2.exists():
            existing = pd.read_csv(OUT_PASS2)
            chunk = pd.concat([existing, chunk], ignore_index=True)
        chunk.to_csv(OUT_PASS2, index=False)

    new_df = pd.read_csv(OUT_PASS2)

    # Save unclassified for Pass 3
    unclassified = new_df[new_df["adoption_label"] == "unclassified"][["full_name"]]
    unclassified.to_csv(OUT_UNRES, index=False)

    # Summary
    total_proc    = len(new_df)
    n_agentic     = (new_df["adoption_label"] == "agentic").sum()
    n_ai_assisted = (new_df["adoption_label"] == "ai_assisted").sum()
    n_unclassified = (new_df["adoption_label"] == "unclassified").sum()

    print()
    print("=" * 55)
    print(f"Total processed   : {total_proc:,}")
    print(f"Agentic (Pass 2)  : {n_agentic:,}  ({n_agentic/total_proc*100:.1f}%)")
    print(f"AI-assisted       : {n_ai_assisted:,}  ({n_ai_assisted/total_proc*100:.1f}%)")
    print(f"Unclassified      : {n_unclassified:,}  ({n_unclassified/total_proc*100:.1f}%)  -> pass to stage3c")
    print()
    print(f"Saved: {OUT_PASS2}")
    print(f"Saved: {OUT_UNRES}")

if __name__ == "__main__":
    main()
